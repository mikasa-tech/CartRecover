"""Generates DATA_DICTIONARY.md + schema.sql from the dictionary (docs can't drift from code)."""
from __future__ import annotations

from pathlib import Path

from cartrecovery.domain.dictionary import ENTITIES, ENUMS
from cartrecovery.repositories.schema import ddl, gt_ddl


def build(out_dir: str = "docs") -> None:
    d = Path(out_dir); d.mkdir(exist_ok=True)
    md = ["# Data Dictionary\n", "_Generated by `python -m cartrecovery.docs`; do not edit by hand._\n"]
    for name, e in ENTITIES.items():
        md.append(f"\n## `{name}`\n{e['desc']}\n\n**PK:** `{e['pk']}`  ")
        md.append("**FKs:** " + (", ".join(f"`{c}` -> `{r}`" for c, r in e["fks"].items()) or "none") + "\n")
        md.append("| field | type | required | allowed / validation | unit | unique |\n|---|---|---|---|---|---|")
        for f, t, req, allowed, unit, uniq in e["fields"]:
            md.append(f"| `{f}` | {t} | {'yes' if req else 'no'} | {allowed} | {unit} | {'yes' if uniq else ''} |")
    md.append("\n## Enumerations\n")
    md += [f"- **{k}**: {', '.join(v)}" for k, v in ENUMS.items()]
    md.append("\n## Ground truth (separate DB/file, never a feature)\n`gt_id, issue_type, entity, entity_id, expected_decision, note`")
    (d / "DATA_DICTIONARY.md").write_text("\n".join(md) + "\n")
    (d / "schema.sql").write_text(ddl() + "\n\n-- separate ground-truth database\n" + gt_ddl() + "\n")


if __name__ == "__main__":
    build()
